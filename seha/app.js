function answer(q){
  var best = null, score = 0;
  QA.forEach(function(item){
    var s = 0;
    item.k.forEach(function(kw){ if(q.indexOf(kw) !== -1) s += kw.length; });
    if(s > score){ score = s; best = item; }
  });
  return best ? best.a : FALLBACK;
}
var box = document.getElementById('answer'), txt = document.getElementById('answerText');
function ask(q){
  if(!q || !q.trim()) return;
  txt.textContent = answer(q); box.hidden = false;
  document.getElementById('answerListen').onclick = function(){ speak(txt.textContent); };
}
document.getElementById('askBtn').addEventListener('click', function(){ ask(document.getElementById('q').value); });
document.getElementById('q').addEventListener('keydown', function(e){ if(e.key === 'Enter') ask(e.target.value); });
document.querySelectorAll('.quick button').forEach(function(b){
  b.addEventListener('click', function(){ ask(b.getAttribute('data-q')); });
});
