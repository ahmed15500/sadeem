// Rafiqa prototype — voice read-aloud + simple Arabic FAQ assistant (runs fully on-device)
function speak(text){
  try{
    var u = new SpeechSynthesisUtterance(text);
    u.lang = 'ar-EG'; u.rate = 0.95;
    speechSynthesis.cancel(); speechSynthesis.speak(u);
  }catch(e){ /* speech not available on this device */ }
}
document.querySelectorAll('[data-speak]').forEach(function(b){
  b.addEventListener('click', function(){ speak(b.getAttribute('data-speak')); });
});

